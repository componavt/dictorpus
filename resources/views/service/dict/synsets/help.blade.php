        <section id="synset-help-basics" aria-labelledby="synset-help-basics-title">
            <h2 id="synset-help-basics-title">1. Основные понятия</h2>
            <p>Участник синсета — конкретное значение слова, а не вся словарная статья. При выборе участника или партнёра проверяйте номер значения и толкование.</p>
            <p>Ядро и периферия определяются типом синонимии: к ядру относятся участники с типом полной синонимии, к периферии — с другими выбранными типами. Доминанта выбирается отдельно; большая корпусная частота не назначает её автоматически.</p>
            <p>Различайте три независимых результата работы:</p>
            <ol>
                <li>Подтверждено значение конкретного слова в корпусном предложении.</li>
                <li>Пара значений внесена в словарную сочетаемость.</li>
                <li>Конкретная пара употреблений прикреплена как подтверждающий пример.</li>
            </ol>
            <p>Одна отметка не заменяет другую. Внесённая пара ещё не означает, что любые её вхождения в одном предложении образуют нужное сочетание.</p>
