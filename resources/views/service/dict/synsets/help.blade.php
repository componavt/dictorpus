                <li>Совпадение грамматических наборов не доказывает синтаксическую связь.</li>
                <li>Прочерк или пустая ячейка не доказывают невозможность сочетания.</li>
                <li>Проверенный партнёр не означает, что проверено исходное употребление.</li>
                <li>Галочка внесённости не подтверждает связь этих двух вхождений в текущем предложении.</li>
                <li>Число предложений не равно числу повторений слов или прикреплённых подтверждений.</li>
