        <section id="synset-help-delete" aria-labelledby="synset-help-delete-title">
            <h2 id="synset-help-delete-title">12. Открепление, удаление и исключение примера</h2>
            <dl>
                <dt>«Открепить пример»</dt>
                <dd>Убирает связь конкретной пары употреблений с записью сочетаемости. Сама сочетаемость, предложение и оценки сохраняются. Действие требует подтверждения.</dd>
                <dt>«Удалить пару из словаря»</dt>
                <dd>Удаляет общую запись сочетаемости источника с партнёром, а не только текущий пример. Прикреплённые подтверждения удаляются из этой записи; корпусные предложения и оценки остаются. Внимательно прочитайте подтверждение.</dd>
                <dt>Оценка 0</dt>
                <dd>Исключает употребление из подходящих примеров исходного значения. Не удаляет словарную пару или корпусный текст.</dd>
                <dt>Корзина участника в основной форме</dt>
                <dd>Меняет состав синсета после сохранения. Не означает удаление словарной статьи.</dd>
            </dl>
