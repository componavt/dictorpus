        <section id="synset-help-comparison" aria-labelledby="synset-help-comparison-title">
            <h2 id="synset-help-comparison-title">6. Режим «Сравнение»: внесённые записи</h2>
            <p>Эта матрица показывает, у каких участников уже записана сочетаемость с данным значением партнёра в данной категории. Столбцы — участники синсета; строки — значения партнёров, сгруппированные по категориям.</p>
            <h3>Обозначения и действия</h3>
<ul>
    <li>Галочка — сочетаемость внесена в данной категории. При наведении показывается сохранённое русское пояснение. Пользователь с правом редактирования может нажать галочку, чтобы открыть существующую запись.</li>
    <li>Пустая ячейка позволяет открыть добавление сочетания с уже выбранными исходным значением, партнёром и категорией. Плюс становится видимым при наведении или фокусе. Нажатие открывает форму, но ещё не сохраняет запись.</li>
    <li>«Примеры» — переход к корпусному поиску пары. Ссылка показывается, если при предварительной проверке найдены употребления. Найденные контексты не обязательно проверены или прикреплены к словарной записи.</li>
    <li>«Прикреплено: N» — число сохранённых подтверждающих примеров у внесённой сочетаемости. Нажатие открывает их просмотр в отдельной вкладке.</li>
    <li>«Нет прикреплённых» — запись сочетаемости есть, но к ней ещё не прикреплены подтверждающие примеры.</li>
</ul>
<p class="synset-help-note">Пустая ячейка означает отсутствие записи в этой категории, а не невозможность сочетания. Запись может существовать в другой категории. Наличие корпусных находок и наличие прикреплённых подтверждений — разные признаки.</p>

<h3>Число прикреплённых примеров и источники</h3>
<p>Под ссылкой «Прикреплено: N» показана разбивка подтверждений по подкорпусам. У диалектных текстов дополнительно указываются сокращения диалектов. При наведении на подпись показываются полные названия.</p>
<p>Общее число учитывает записи прикрепления конкретных пар употреблений, а не количество разных текстов или предложений. В одном предложении могут быть прикреплены разные пары употреблений.</p>
<p>Если текст относится к нескольким подкорпусам, его подтверждения учитываются в каждой соответствующей группе. Поэтому сумма чисел по группам может превышать общее число прикреплённых примеров.</p>
<p>«Подкорпус не указан» или «диалект не указан» означает отсутствие соответствующих сведений у текста, а не отрицательную оценку примера. Подробнее о просмотре подтверждений — в <a href="#synset-help-attach">разделе 11</a>.</p>
            <h3>Выбор участников и различия</h3>
            <p>Флажки «Участники сравнения», «Выбрать всех» и «Снять выбор» меняют только отображение. Они не меняют состав синсета. Здесь сравнение перестраивается сразу.</p>
            <p>«Только различия» оставляет строки, где запись есть хотя бы у одного выбранного участника, но отсутствует хотя бы у другого. Нужно выбрать минимум двух участников.</p>
            <p>Сравнивается наличие записей в конкретной категории. Различия русских пояснений не учитываются: две внесённые записи с разными пояснениями не становятся различием только из-за текста.</p>
            <p>Режим представления, выбранные участники и флажок различий запоминаются в этом браузере отдельно для синсета. Это настройки просмотра, а не изменение словарных данных.</p>
            <h3>Переход к примерам</h3>
            <p>«Примеры» в этой матрице открывает широкий поиск: во всём предложении, без обязательного согласования и без ограничения только проверенными партнёрами. Найденные контексты нужно проверить самостоятельно. При необходимости сузьте интервал, подкорпус, формы или проверенность.</p>
