        <section id="synset-help-troubleshooting" aria-labelledby="synset-help-troubleshooting-title">
            <h2 id="synset-help-troubleshooting-title">14. Если результат выглядит неожиданно</h2>
            <dl>
                <dt>Нет пары в сравнении внесённых записей</dt>
                <dd>Проверьте структурированную запись, выбранных участников и «Только различия». Текстовая сводка сама строки не создаёт.</dd>
                <dt>Нет корпусных находок</dt>
                <dd>Проверьте участников, интервал, согласование, проверенность, формы, часть речи партнёра и подкорпусы. Прочерк относится только к текущим условиям.</dd>
                <dt>Пара есть в одной сводке и отсутствует в другой</dt>
                <dd>Уточните, сравниваете ли словарные записи или корпусные находки и одинаковы ли фильтры.</dd>
                <dt>После изменения состава осталась старая сводка</dt>
                <dd>Сохраните синсет и откройте актуальную страницу. Сводки строятся по сохранённым участникам.</dd>
                <dt>Значение больше не входит в указанный синсет</dt>
                <dd>Откройте редактор заново из актуального состава, не продолжайте работу по устаревшей ссылке.</dd>
                <dt>После правки в другой вкладке таблица не изменилась</dt>
                <dd>Обновите её или вернитесь предусмотренной ссылкой. Открытая вкладка не обязательно синхронизируется автоматически.</dd>
            </dl>
