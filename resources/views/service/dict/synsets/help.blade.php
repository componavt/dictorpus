        <section id="synset-help-members" aria-labelledby="synset-help-members-title">
            <h2 id="synset-help-members-title">3. Создание, состав и порядок участников</h2>

            <h3 id="synset-help-create">Создание синсета с нуля</h3>
            <ol>
                <li>В списке синсетов выберите язык и нажмите «Создать новый».</li>
                <li>Проверьте язык, выберите часть речи и заполните необходимые текстовые поля.</li>
                <li>В блоке «Искать в словаре» найдите и выберите конкретные значения. Проверяйте номер значения и толкование.</li>
                <li>Сохраните синсет одной из кнопок создания.</li>
            </ol>
            <p>Просто набранный текст не становится участником: значение нужно выбрать из выпадающего списка. Можно выбрать несколько значений.</p>
            <p>Выбранные значения можно сохранить напрямую, без нажатия «добавить». В этом случае они включаются с типом «полные». Чтобы перед сохранением настроить тип синонимии или выбрать доминанту, нажмите «добавить»: значения появятся отдельными строками формы.</p>
            <p>Пустой синсет создать нельзя. Участники должны соответствовать выбранным языку и части речи.</p>
            <h3>Участники и счётчики</h3>
            <p>В редакторе участники разделены на ядро и периферию. У каждого показаны слово, номер значения, толкование, корпусные счётчики и тип синонимии.</p>
            <p>Порядок участников задаётся вручную; доминанта располагается первой в ядре. Корпусная частота служит справочной информацией и не определяет порядок. Основной счётчик учитывает положительные привязки к значению, включая непроверенные: это не число исключительно проверенных хороших примеров. Дополнительные счётчики, если они есть, относятся к оценкам 10 и 7.</p>
            <p>Чтобы изменить доминанту, выберите переключатель у нужного значения и сохраните синсет.</p>
            <h3>Добавление и исключение</h3>
            <ul>
                <li>Просмотрите потенциальных участников. Они предлагаются по сходству русских толкований и полю «Русские синонимы»; это подсказки, а не подтверждённые синонимы.</li>
                <li>При необходимости дополните «Русские синонимы» и нажмите значок обновления списка потенциальных участников.</li>
                <li>У подходящего кандидата нажмите плюс и проверьте тип синонимии.</li>
                <li>Если нужного значения нет среди подсказок, выберите его в блоке «Искать в словаре». Можно сохранить выбранное значение напрямую или сначала нажать «добавить», чтобы настроить тип синонимии и доминанту.</li>
                <li>Для исключения нажмите корзину у участника: строка зачёркивается, и её можно вернуть плюсом до сохранения.</li>
            </ul>
            <p>Изменение состава закрепляется сохранением формы. Не включайте значение только из-за совпадения одного русского слова в толковании. После исключения прежней доминанты проверьте выбор новой.</p>
            <h3 id="synset-help-order">Ручной порядок участников</h3>
            <p>Кнопки «Выше» и «Ниже» перемещают участника внутри ядра или периферии. Для перехода в другую группу измените тип синонимии и сохраните основную форму.</p>
            <p>Доминанта всегда располагается первой в ядре; её кнопки перестановки недоступны. Остальные участники не могут переместиться выше доминанты. На границах групп соответствующие кнопки также недоступны.</p>
            <p>Перестановка сохраняется сразу, без перезагрузки страницы и без нажатия основной кнопки «Сохранить». После успешного ответа обновляется порядок участников в редакторе и представлениях сочетаемости. Сообщение возле списка показывает результат сохранения.</p>
            <p class="synset-help-note">Перед перестановкой сохраните остальные изменения формы. Кнопки порядка доступны после создания синсета; в форме, восстановленной после ошибки проверки, они появятся после успешного сохранения.</p>
            <h3>Сохранение</h3>
            <p>«Сохранить» сохраняет изменения и оставляет вас в редакторе. «Сохранить и вернуться к списку» сохраняет их и открывает список. При создании используются соответствующие кнопки создания; пустой новый синсет создать нельзя.</p>
            <p class="synset-help-note">Перед переходом к сочетаемости, кандидатам или примерам сохраните состав синсета. Нижние сводки строятся по сохранённым данным. Предупреждение о несохранённых изменениях действует не для всех возможных переходов.</p>
