        <section id="synset-help-comparison" aria-labelledby="synset-help-comparison-title">
            <h2 id="synset-help-comparison-title">6. Режим «Сравнение»: внесённые записи</h2>
            <p>Эта матрица показывает, у каких участников уже записана сочетаемость с данным значением партнёра в данной категории. Столбцы — участники синсета; строки — значения партнёров, сгруппированные по категориям.</p>
            <h3>Обозначения и действия</h3>
            <ul>
                <li>Галочка — запись внесена. При наведении показывается сохранённое пояснение; нажатие открывает редактирование.</li>
                <li>Незаполненная ячейка позволяет открыть добавление с выбранными источником, партнёром и категорией. Плюс становится видимым при наведении или фокусе. Нажатие ещё не сохраняет запись.</li>
                <li>«Примеры» открывает корпусный поиск пары, если при предварительной проверке найдены употребления. Это не число прикреплённых подтверждений.</li>
            </ul>
            <p class="synset-help-note">Пустая ячейка означает отсутствие записи в этой категории, а не невозможность сочетания. Запись может существовать в другой категории.</p>
            <h3>Выбор участников и различия</h3>
            <p>Флажки «Участники сравнения», «Выбрать всех» и «Снять выбор» меняют только отображение. Они не меняют состав синсета. Здесь сравнение перестраивается сразу.</p>
            <p>«Только различия» оставляет строки, где запись есть хотя бы у одного выбранного участника, но отсутствует хотя бы у другого. Нужно выбрать минимум двух участников.</p>
            <p>Сравнивается наличие записей в конкретной категории. Различия русских пояснений не учитываются: две внесённые записи с разными пояснениями не становятся различием только из-за текста.</p>
            <p>Режим представления, выбранные участники и флажок различий запоминаются в этом браузере отдельно для синсета. Это настройки просмотра, а не изменение словарных данных.</p>
            <h3>Переход к примерам</h3>
            <p>«Примеры» в этой матрице открывает широкий поиск: во всём предложении, без обязательного согласования и без ограничения только проверенными партнёрами. Найденные контексты нужно проверить самостоятельно. При необходимости сузьте интервал, подкорпус, формы или проверенность.</p>
            <p class="synset-help-back"><a href="#synset-help-contents">К содержанию</a></p>
        </section>

        <section id="synset-help-editor" aria-labelledby="synset-help-editor-title">
            <h2 id="synset-help-editor-title">7. Добавление, изменение и копирование сочетаемости</h2>
            <p>В редакторе проверьте исходное значение в заголовке. Операции относятся к нему, а не ко всему синсету.</p>
            <h3>Новая запись</h3>
            <ol>
                <li>В поле «Слово-партнёр и значение» введите не менее двух символов леммы.</li>
                <li>Выберите значение по номеру и толкованию. Язык партнёра должен совпадать с языком источника.</li>
                <li>Укажите категорию или оставьте «Без категории».</li>
                <li>Проверьте «Русское пояснение». При выборе партнёра подставляется его русское словарное толкование; при необходимости измените его для данной записи.</li>
                <li>«Взять толкование из словаря» заново подставляет словарный текст вместо текущего пояснения.</li>
                <li>Нажмите «Сохранить» и проверьте список внесённых сочетаемостей.</li>
            </ol>
            <p>После добавления категория сохраняется для следующей записи. Стрелка возле категории существующей строки позволяет подставить её в форму нового сочетания.</p>
            <h3>Изменение и дубликаты</h3>
            <p>Карандаш существующей записи открывает редактирование. После правки нажмите «Сохранить»; «Отмена» выходит из редактирования без сохранения текущей правки формы.</p>
            <p>Для одного исходного значения нельзя повторно внести того же партнёра как вторую запись только ради другой категории. Если из пустой ячейки открывается уже существующая пара, система переводит к ней и предупреждает, что её категория может отличаться. Проверьте запись вместо создания дубликата.</p>
            <p>Сочетаемость источника A с партнёром B не следует автоматически считать записью B с A. Проверяйте исходное значение в заголовке.</p>
            <p>После работы используйте «Вернуться к синсету №…»: сводка загрузится заново. При переходе из примеров или кандидатов может быть доступна соответствующая ссылка возврата.</p>
            <h3>Копирование</h3>
            <ol>
                <li>Нажмите «Скопировать из другого слова».</li>
                <li>Выберите источник и нажмите «Показать сочетаемости». Источник и получатель должны быть разными значениями одного языка.</li>
                <li>Отметьте нужные доступные строки и нажмите «Копировать выбранные».</li>
                <li>Проверьте сообщение о добавленных и пропущенных записях.</li>
            </ol>
            <p>Существующие пары получателя не перезаписываются. Если категория или пояснение отличаются, запись отмечается как конфликтующая и остаётся без изменения. Копируются пары, категории и пояснения; подтверждающие корпусные примеры этим действием не переносятся.</p>
            <p>Копирование ускоряет ввод после экспертной проверки, но не доказывает одинаковую сочетаемость синонимов.</p>
            <p class="synset-help-back"><a href="#synset-help-contents">К содержанию</a></p>
        </section>

        <section id="synset-help-matrix-candidates" aria-labelledby="synset-help-matrix-candidates-title">
            <h2 id="synset-help-matrix-candidates-title">8. Корпусные кандидаты всех участников</h2>
            <p>Кнопка «Корпусные кандидаты всех участников» открывает другую матрицу: с какими значениями партнёров участники встретились в корпусе при выбранных условиях.</p>
            <p>Это не матрица внесённых записей. Находка может быть непроверенным вариантом разбора или случайным соседством.</p>
            <h3>Условия</h3>
            <p>Выберите участников и нажмите «Показать кандидатов», чтобы применить выбор. Состав синсета не меняется.</p>
            <p>Можно задать проверенность источника и партнёра, формы исходного слова, часть речи партнёра, интервал либо поиск во всём предложении, согласование и подкорпусы.</p>
            <p>Начальные условия этой страницы включают интервал −1…+1 и требование согласования. У других входов в поиск настройки могут отличаться.</p>
            <h3>Ячейки и счётчики</h3>
            <ul>
                <li>Основное число — количество разных предложений с парой при текущих условиях. Нажатие открывает контексты данной пары в новой вкладке.</li>
                <li>«пр.» — предложения с проверенным значением партнёра.</li>
                <li>«непр.» — предложения с непроверенным вариантом значения партнёра.</li>
                <li>Галочка — пара уже внесена в словарную сочетаемость.</li>
                <li>Прочерк — находок при текущих условиях нет.</li>
            </ul>
            <p>Одно предложение может содержать проверенное и непроверенное употребления партнёра: «пр.» и «непр.» могут пересекаться, их сумма не обязана равняться общему числу. Проверенность источника задаётся отдельно.</p>
            <h3>Отбор строк</h3>
            <ul>
                <li>«Все партнёры» — все найденные строки выбранных участников.</li>
                <li>«Общие партнёры» — значения партнёров, найденные у каждого выбранного участника.</li>
                <li>«Различия по наличию находок» — находки есть у части, но не у всех выбранных участников.</li>
                <li>«Есть невнесённые пары» — хотя бы у одного выбранного участника есть находки, но пара ещё не внесена. Прочерк не считается невнесённой находкой.</li>
            </ul>
            <p>Сравнивается наличие находок, не их частота: числа 2 и 15 означают наличие у обоих участников. Для сравнения нужны минимум два участника; при одном показываются его находки.</p>
            <p>В строке с невнесёнными парами могут оставаться и внесённые пары других участников. Число найденных значений-партнёров и число показанных строк различаются при включённых фильтрах.</p>
            <p class="synset-help-back"><a href="#synset-help-contents">К содержанию</a></p>
        </section>

        <section id="synset-help-single-candidates" aria-labelledby="synset-help-single-candidates-title">
            <h2 id="synset-help-single-candidates-title">9. Кандидаты отдельного участника</h2>
            <p>«Кандидаты на сочетаемость» возле участника открывает индивидуальную сводку: значения соседних слов, числа предложений и текстов, проверенные и непроверенные партнёры, внесённость пары.</p>
            <p>Выдача упорядочена прежде всего по числу предложений, затем по числу текстов. Есть собственная пагинация. Значения одной леммы могут попасть на разные страницы: группировка не гарантирует, что все они собраны вместе.</p>
            <p>Откройте примеры перспективного кандидата, проверьте разбор и только затем решайте, вносить ли пару. Внесённость и проверенность употреблений оценивайте раздельно.</p>
