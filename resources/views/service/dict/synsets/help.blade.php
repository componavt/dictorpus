        <section id="synset-help-workflow" aria-labelledby="synset-help-workflow-title">
            <h2 id="synset-help-workflow-title">13. Рекомендуемый порядок работы</h2>
            <ol>
                <li>Проверьте номера значений участников, типы синонимии и доминанту.</li>
                <li>Сохраните основную форму.</li>
                <li>Просмотрите внесённую сочетаемость «По словам».</li>
                <li>В «Сравнении» выберите участников и проверьте различия внесённых записей.</li>
                <li>Откройте кандидатов всех участников и примените одинаковые условия поиска.</li>
                <li>При необходимости отберите общих партнёров, различия или невнесённые пары.</li>
                <li>По числу в ячейке откройте контексты конкретной пары.</li>
                <li>Проверьте значения обоих слов и связь между ними.</li>
                <li>Внесите или уточните словарную сочетаемость.</li>
                <li>Прикрепите подходящие конкретные употребления как подтверждения.</li>
                <li>Вернитесь к синсету и проверьте обновлённую сводку.</li>
                <li>Если синсет готов по принятому рабочему процессу, отдельно измените его статус в списке.</li>
            </ol>
            <p>Это рекомендуемая последовательность, а не требование интерфейса выполнять операции строго в таком порядке.</p>
