        <section id="synset-help-summary" aria-labelledby="synset-help-summary-title">
            <h2 id="synset-help-summary-title">4. Текстовые поля синсета и заметки об участниках</h2>

            <h3>Общее значение</h3>
            <p>Краткая формулировка значения, объединяющего участников синсета. Поле находится в верхней части формы, под языком, и заполняется одной строкой.</p>
            <p>Описывайте общее для ряда значение, а не все значения входящих в него слов. Уточнения об отдельных участниках не следует включать в общую формулировку. Общее значение показывается в списке синсетов и в шапке открытого синсета; по нему можно искать.</p>

            <h3>Этимология</h3>
            <p>Текстовые сведения о происхождении слов ряда и этимологические комментарии, существенные для описания синсета. Если замечание относится только к одному участнику, укажите, к какому именно слову и значению оно относится.</p>
            <p>Поле поддерживает форматирование. Его заполнение само по себе не изменяет словарные статьи участников.</p>

            <h3>Потенциальные кандидаты</h3>
            <p>Экспертные заметки о возможных участниках ряда: какие слова и значения стоит проверить, почему они рассматриваются и какие вопросы ещё требуют решения.</p>
            <p>Это текстовое поле, а не список выбранных участников. Запись слова здесь не добавляет его в ядро или периферию. Чтобы включить значение в синсет, выберите его через поиск в словаре или добавьте из списка предложений и сохраните состав.</p>
            <p>Не путайте поле «Потенциальные кандидаты» с блоком «Возможные кандидаты»: поле содержит ваши заметки, а блок — автоматически предложенные значения с действиями добавления.</p>

            <h3>Русские синонимы</h3>
            <p>Русские слова и выражения, передающие значение ряда. Это отдельное текстовое поле, а не перечень русских словарных статей, включённых в синсет.</p>
            <p>Поле используется при подборе возможных участников. После его изменения нажмите значок обновления возле блока «Возможные кандидаты», чтобы заново получить предложения с учётом введённого текста.</p>
            <p>Предложение программы ещё не подтверждает синонимию: проверьте конкретное значение и только затем решайте, включать ли его в синсет. Обновление предложений не заменяет сохранение основной формы.</p>

            <h3>Дополнительные сведения о сочетаемости</h3>
            <p>В режиме «По словам» под сочетаемостью каждого участника находится отдельное поле «Дополнительные сведения о сочетаемости». Здесь можно записать особенности употребления, ограничения сочетаемости и другие пояснения, относящиеся к этому участнику именно в данном синсете.</p>
            <p>Заметка связана с участником конкретного синсета. Она не является общим комментарием ко всему ряду и не заменяет описание этого значения в словарной статье. Источники указывайте кратко в квадратных скобках.</p>
            <p>Текст заметки не разбирается автоматически на отдельные сочетания. Чтобы пара появилась в списке внесённых сочетаемостей и в матрице сравнения, добавьте её через редактор сочетаемости. Подтверждающие корпусные примеры также прикрепляются отдельно.</p>

            <h3>Форматирование и сохранение</h3>
            <p>«Этимология», «Потенциальные кандидаты» и заметки о сочетаемости участников имеют панель форматирования. «Общее значение» — однострочное поле, «Русские синонимы» — обычное многострочное поле.</p>
            <p>Изменения текстовых полей сохраняются кнопками основной формы синсета. Это относится и к заметкам участников в нижнем блоке сочетаемости: после их редактирования используйте «Сохранить» или «Сохранить и вернуться к списку».</p>
            <p class="synset-help-note">Ввод текста, его форматирование, обновление возможных кандидатов и переключение режима сочетаемости не заменяют сохранение формы. Кнопка «Сохранить» в отдельном редакторе сочетаемости сохраняет запись сочетания, а не текстовые поля открытой формы синсета.</p>

