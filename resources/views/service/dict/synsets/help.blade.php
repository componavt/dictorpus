        <section id="synset-help-members" aria-labelledby="synset-help-members-title">
            <h2 id="synset-help-members-title">3. Состав синсета, доминанта и сохранение</h2>
            <h3>Участники и счётчики</h3>
            <p>В редакторе участники разделены на ядро и периферию. У каждого показаны слово, номер значения, толкование, корпусные счётчики и тип синонимии.</p>
            <p>Ядро упорядочено по убыванию корпусной частоты. Основной счётчик учитывает положительные привязки к значению, включая непроверенные: это не число исключительно проверенных хороших примеров. Дополнительные счётчики, если они есть, относятся к оценкам 10 и 7.</p>
            <p>Чтобы изменить доминанту, выберите переключатель у нужного значения и сохраните синсет.</p>
            <h3>Добавление и исключение</h3>
            <ul>
                <li>Просмотрите потенциальных участников. Они предлагаются по сходству русских толкований и полю «Русские синонимы»; это подсказки, а не подтверждённые синонимы.</li>
                <li>При необходимости дополните «Русские синонимы» и нажмите значок обновления списка потенциальных участников.</li>
                <li>У подходящего кандидата нажмите плюс и проверьте тип синонимии.</li>
                <li>Если нужного значения нет среди подсказок, воспользуйтесь блоком «Искать в словаре», выберите значение и нажмите «добавить».</li>
                <li>Для исключения нажмите корзину у участника: строка зачёркивается, и её можно вернуть плюсом до сохранения.</li>
            </ul>
            <p>Изменение состава закрепляется сохранением формы. Не включайте значение только из-за совпадения одного русского слова в толковании. После исключения прежней доминанты проверьте выбор новой.</p>
            <h3>Сохранение</h3>
            <p>«Сохранить» сохраняет изменения и оставляет вас в редакторе. «Сохранить и вернуться к списку» сохраняет их и открывает список. При создании используются соответствующие кнопки создания; пустой новый синсет создать нельзя.</p>
            <p class="synset-help-note">Перед переходом к сочетаемости, кандидатам или примерам сохраните состав синсета. Нижние сводки строятся по сохранённым данным. Предупреждение о несохранённых изменениях действует не для всех возможных переходов.</p>
            <p class="synset-help-back"><a href="#synset-help-contents">К содержанию</a></p>
        </section>

        <section id="synset-help-summary" aria-labelledby="synset-help-summary-title">
            <h2 id="synset-help-summary-title">4. Текстовая сводка и записи сочетаемости</h2>
            <p>Поле «Исходная экспертная сводка (текст)» хранит общий текст. Оно не заменяет отдельные записи сочетаемости и не разбирается автоматически на пары для матрицы.</p>
            <p>Чтобы пара появилась в структурированном списке и сравнении, внесите её в сочетаемость конкретного участника. Изменение текстовой сводки такую запись не создаёт.</p>
