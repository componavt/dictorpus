        <section id="synset-help-attach" aria-labelledby="synset-help-attach-title">
            <h2 id="synset-help-attach-title">11. Просмотр и прикрепление подтверждающих примеров</h2>

            <h3>Как открыть прикреплённые примеры</h3>
            <p>В матрице «Сравнение» нажмите «Прикреплено: N» у нужного сочетания. В отдельной вкладке откроются подтверждения, уже связанные с этой словарной записью. В заголовке показаны исходное слово и партнёр с номерами значений.</p>
            <p>Не путайте этот переход со ссылкой «Примеры». «Примеры» запускает корпусный поиск пары, а «Прикреплено: N» показывает сохранённые подтверждения. Состав этих списков и их количество могут различаться.</p>

            <h3>Что показано в карточке</h3>
            <p>Карточка содержит текст примера с выделенными употреблениями. Под ним указаны сокращённые названия подкорпусов; для диалектного материала дополнительно показаны диалекты. При наведении на подпись можно прочитать полные названия.</p>
            <p>Если доступен исходный корпусный текст, его название показано ссылкой под примером. Перейдите по ней, чтобы посмотреть более широкий контекст.</p>
            <p>Подписи «Подкорпус не указан» и «диалект не указан» относятся к сведениям об источнике. Они не означают, что пример отклонён или не проверен.</p>
            <p>Эта страница предназначена для просмотра. Действия проверки значений, прикрепления и открепления выполняются в поиске примеров. Чтобы вернуться к сводке синсета, используйте вкладку «Сочетаемость» в общей шапке или исходную вкладку браузера с матрицей.</p>

            <h3>Условия прикрепления нового подтверждения</h3>
            <p>Откройте корпусный поиск пары по ссылке «Примеры». Для прикрепления нужны следующие условия:</p>
            <ul>
                <li>Пара уже внесена в сочетаемость исходного значения.</li>
                <li>Проверен конкретный контекст и реальная связь слов.</li>
                <li>У обоих употреблений подтверждены нужные значения, не только леммы.</li>
                <li>Оба слова принадлежат одному предложению и доступны в показываемом контексте. Для сохранённого фрагмента не предлагается прикрепить слово, скрытое за его пределами.</li>
            </ul>
            <p>Нажмите «Прикрепить как подтверждающий пример» у нужной пары. При нескольких вхождениях сверяйте словоформы и позиции: прикрепляется конкретная пара употреблений, а не предложение вообще.</p>
            <p>Если действие недоступно, проверьте перечисленные условия. После изменения разметки обновите страницу, если список действий ещё не соответствует данным.</p>

            <h3>После прикрепления</h3>
            <p>Вернитесь к сводке сочетаемости. Если матрица осталась открыта в другой вкладке, обновите её, чтобы увидеть актуальное число подтверждений. Уже открытая страница просмотра прикреплённых примеров также требует обновления после изменений в другой вкладке.</p>
            <p>Открепление подтверждения и удаление самой сочетаемости — разные операции. Их последствия описаны в <a href="#synset-help-delete">разделе 12</a>.</p>

