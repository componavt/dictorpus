        <section id="synset-help-open" aria-labelledby="synset-help-open-title">
            <h2 id="synset-help-open-title">2. Поиск и открытие синсета</h2>
            <p>Откройте список синсетов. Выберите язык, при необходимости часть речи, статус и количество записей на странице. Дополнительные поля позволяют искать по участникам и текстовым полям синсета.</p>

            <ul>
                <li>«Лемма» — поиск по леммам участников синсета, включая ядро и периферию.</li>
                <li>«Общее значение» — поиск по одноимённому полю синсета.</li>
                <li>«Русские синонимы» — поиск по тексту этого поля, а не по русским толкованиям всех участников.</li>
            </ul>

            <p>В текстовых полях используется совпадение со всей строкой. Для неточного поиска задайте шаблон: <code>%</code> заменяет любое количество символов, <code>_</code> — один символ. Проценты по краям автоматически не добавляются.</p>
            <ul>
                <li><code>грустный</code> — строка «грустный» целиком.</li>
                <li><code>грустный%</code> — строка, начинающаяся с «грустный».</li>
                <li><code>%грустный%</code> — строка, содержащая «грустный», например в перечне русских синонимов.</li>
            </ul>

            <p>После задания условий нажмите кнопку показа результатов. В списке отображаются общее значение, доминанта, ядро, периферия, сочетаемость и потенциальные участники. Номер возле слова различает его значения; при наведении на номер показывается толкование.</p>
            <p>Карандаш открывает редактор синсета. Для создания используйте «Создать новый». Изменение данных доступно пользователям с правом редактирования словаря.</p>
            <p>Публикация и возврат в черновики выполняются отдельным действием в списке. Подсказка показывает, что произойдёт при нажатии. Сохранение формы само по себе не заменяет изменение статуса.</p>

            <h3>Навигация внутри синсета</h3>
            <p>Общая шапка показывает раздел словаря и номер синсета. «Редактор» открывает основную форму, «Сочетаемость» переводит к блоку сочетаемости, «Примеры» открывает корпусных кандидатов участников. Ссылка «Помощь» открывает соответствующий раздел этой справки в отдельной вкладке.</p>
            <p>На страницах работы с отдельным участником справа могут отображаться «Леммы: …» и «История изменений». Это переходы к словарной статье участника и её истории. Ссылка на лемму на страницах поиска примеров и редактора сочетаемости ведёт к соответствующему значению статьи.</p>

