        <section id="synset-help-examples" aria-labelledby="synset-help-examples-title">
            <h2 id="synset-help-examples-title">10. Поиск и проверка примеров</h2>
            <h3>Одно значение или пара</h3>
            <p>«Все примеры» открывает поиск исходного значения. Пока партнёр не выбран, «Условия сочетания» скрыты. После выбора партнёра блок появляется; очистка поля возвращает поиск только источника.</p>
            <p>Партнёр выбирается из значений, найденных корпусным поиском при текущих условиях. Для ручного внесения пары без найденного корпусного материала используйте редактор сочетаемости.</p>
            <p>Проверенность исходного значения и партнёра задаётся независимо. Без соответствующих ограничений поиск включает непроверенные варианты; отклонённые употребления с оценкой 0 не входят в обычную положительную выборку.</p>
            <h3>Расстояние, согласование, формы и подкорпусы</h3>
            <p>Расстояние — позиция партнёра относительно источника в исходном предложении: −1 — непосредственно перед ним, +1 — непосредственно после него. Начало диапазона не должно превышать конец.</p>
            <p>«Искать во всём предложении» снимает ограничение расстояния, сохраняя интервал для возврата к ограниченному окну. Совместное присутствие в предложении не доказывает синтаксическую или смысловую связь.</p>
            <p>«Учитывать согласование» требует наличия совместимого разбора с общим грамматическим набором. Это морфологический фильтр, не полноценная проверка синтаксической связи. Для сочетаний, не требующих такого совпадения, он может отсекать подходящие примеры.</p>
            <p>В формах исходного слова и подкорпусах можно выбрать несколько значений: подходит любая выбранная форма и любой выбранный подкорпус. Пустой выбор не ограничивает поиск по этому признаку.</p>
            <h3>Карточки и оценки</h3>
            <p>Результаты считаются и разбиваются на страницы по разным предложениям. Несколько исходных употреблений одного предложения могут дать несколько карточек внутри него. Первее выводятся предложения с более высокой оценкой подходящего исходного употребления.</p>
            <p>Подсвечиваются конкретные найденные употребления, не все внешне похожие слова. Верхняя линия в ограниченном окне показывает соседей в интервале. Расстояния считаются по исходному предложению, даже если показан фрагмент.</p>
            <p>В карточке могут быть текст или сохранённый фрагмент, перевод, ссылка на корпусный текст, оценка и действия редактирования.</p>
            <ul>
                <li>10 — лучший пример.</li>
                <li>7 — отличный пример.</li>
                <li>5 — хороший пример.</li>
                <li>0 — неподходящее употребление для исходного значения.</li>
                <li>1 — непроверенный вариант, не равный экспертно подтверждённому.</li>
            </ul>
            <p>Оценка карточки относится к исходному употреблению. Она не подтверждает автоматически партнёра и не создаёт словарную пару. Оценка 0 не удаляет корпусное предложение.</p>
            <p>Чтобы проверить разбор, нажмите нужное слово и просмотрите значения и грамматические разборы. Исходное значение не следует подтверждать только потому, что оно является целью поиска. Партнёра проверяйте отдельно.</p>
            <p>Карандаш открывает редактор примера. После сохранения используйте возврат ко всем примерам, чтобы сохранить контекст поиска. После изменения оценки или разметки состав и порядок результатов могут измениться.</p>
            <p>В сохранённом фрагменте редактируется только целевое слово. Для контекста используйте «Показать исходное предложение»; не пытайтесь через фрагмент изменить разбор остальных слов.</p>
            <p class="synset-help-back"><a href="#synset-help-contents">К содержанию</a></p>
        </section>

        <section id="synset-help-attach" aria-labelledby="synset-help-attach-title">
            <h2 id="synset-help-attach-title">11. Прикрепление подтверждающего примера</h2>
            <p>Для прикрепления нужны следующие условия:</p>
            <ul>
                <li>Пара уже внесена в сочетаемость исходного значения.</li>
                <li>Проверен конкретный контекст и реальная связь слов.</li>
                <li>У обоих употреблений подтверждены нужные значения, не только леммы.</li>
                <li>Оба слова принадлежат одному предложению и доступны в показываемом контексте. Для фрагмента не предлагается прикрепить скрытое за его пределами слово.</li>
            </ul>
            <p>Нажмите «Прикрепить как подтверждающий пример» у нужной пары. При нескольких вхождениях сверяйте словоформы и позиции: прикрепляется конкретная пара употреблений, не предложение вообще.</p>
            <p>Если действие недоступно, проверьте перечисленные условия. После изменения разметки обновите страницу, если список действий ещё не соответствует данным.</p>
