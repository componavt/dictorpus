        <section id="synset-help-words" aria-labelledby="synset-help-words-title">
            <h2 id="synset-help-words-title">5. Сочетаемость: режим «По словам»</h2>
            <p>Ниже основной формы расположен блок «Сочетаемость членов синсета». В режиме «По словам» участники показаны отдельными блоками ядра и периферии; у доминанты есть соответствующая пометка.</p>
            <p>У каждого участника доступны:</p>
            <ul>
                <li>Карандаш — редактор его сочетаемости.</li>
                <li>«Все примеры» — поиск употреблений именно этого значения.</li>
                <li>«Кандидаты на сочетаемость» — корпусная сводка потенциальных партнёров этого участника.</li>
            </ul>
            <p>Внесённые пары сгруппированы по категориям. Пустой список означает отсутствие внесённых записей, а не отсутствие сочетаемости у слова.</p>
            <p>У разных переходов могут различаться начальные настройки. В частности, ссылка на кандидатов из блока участника открывает поиск без требования согласования. Перед сопоставлением результатов проверяйте фактические условия формы.</p>
            <p class="synset-help-back"><a href="#synset-help-contents">К содержанию</a></p>
