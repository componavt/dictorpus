        <section id="synset-help-open" aria-labelledby="synset-help-open-title">
            <h2 id="synset-help-open-title">2. Как открыть синсет</h2>
            <p>Откройте список синсетов, выберите язык и при необходимости другие условия поиска. В списке показаны доминанта, ядро, периферия, сочетаемость, потенциальные участники и русские синонимы. Номер возле слова различает его значения; при наведении на номер в списке показывается толкование.</p>
            <p>Нажмите карандаш, чтобы открыть редактор. Для создания нового синсета используйте «Создать новый». Редактирование доступно пользователям с правом редактирования словаря.</p>
            <p>В списке есть отдельное действие публикации или возврата в черновики. Подсказка показывает действие, которое будет выполнено при нажатии. Сохранение формы редактора и изменение статуса — разные операции.</p>
